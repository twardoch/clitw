"""Private wrapper registry, native process configuration and header templates."""

from __future__ import annotations

import base64
import json
import os
import re
import sys
import tempfile
from pathlib import Path
from urllib.parse import urlsplit

from clitwy.paths import home, provider_argv, registry_dir

NAME = re.compile(r"mcx-[a-z0-9]+(?:-[a-z0-9]+)*\Z")
HEADER = re.compile(r"([A-Za-z][\w-]*):(?:([A-Za-z][\w-]*) )?env:([A-Z_][A-Z0-9_]*)(?:\+env:([A-Z_][A-Z0-9_]*))?\Z")
STATIC = re.compile(
    r"(?i:accept:application/json|user-agent:(?:mcxadmin-openapi|clitwy?)/1\.0|(?:anthropic|cartesia)-version:\d{4}-\d{2}-\d{2})\Z"
)
NO_BASE = "https://unconfigured.invalid"


def valid_url(value: str, *, base: bool = False) -> bool:
    parsed = urlsplit(value)
    local = parsed.scheme == "http" and parsed.hostname in {"localhost", "127.0.0.1", "::1"}
    return bool(
        (parsed.scheme == "https" or local)
        and parsed.hostname
        and parsed.username is None
        and parsed.password is None
        and not parsed.fragment
        and not any(c.isspace() for c in value)
        and (not base or not parsed.query and not any(c in value for c in "{}"))
    )


def header_args(binding: str, environment: dict[str, str]) -> list[str]:
    """Resolve only named variables, passing any derived values to mcp2cli by reference."""
    argv = []
    for i, header in enumerate(filter(None, binding.split(","))):
        if STATIC.fullmatch(header):
            argv.extend(("--auth-header", header))
            continue
        match = HEADER.fullmatch(header)
        if not match:
            raise ValueError("auth headers require HEADER:[SCHEME ]env:VARIABLE")
        field, prefix, first, second = match.groups()
        value = environment.get(first, "")
        if second:
            other = environment.get(second, "")
            if not other:
                continue
            if value:
                value += ":" + other
                if prefix == "Basic":
                    value = base64.b64encode(value.encode()).decode("ascii")
        if not value:
            continue
        if any(ord(c) < 32 for c in value):
            raise ValueError("credential contains a control character")
        var = f"CLITW_OPENAPI_HEADER_{i}"
        environment[var] = (prefix + " " if prefix else "") + value
        argv.extend(("--auth-header", f"{field}:env:{var}"))
    return argv


def registry() -> dict[str, dict]:
    target = registry_dir() / "openapi.json"
    if not target.exists():
        return {}
    data = json.loads(target.read_text(encoding="utf-8"))
    if not isinstance(data, dict):
        raise TypeError("invalid OpenAPI registry")
    return data


def atomic(path: Path, data: bytes, mode: int = 0o600) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    with tempfile.NamedTemporaryFile(dir=path.parent, delete=False) as tmp:
        stage = Path(tmp.name)
        try:
            tmp.write(data)
            tmp.flush()
        except BaseException:
            stage.unlink(missing_ok=True)
            raise
    try:
        stage.chmod(mode)
        os.replace(stage, path)
    finally:
        stage.unlink(missing_ok=True)


def wrapper(name: str, executable: str | None = None, *, package: str = "clitwy") -> bytes:
    if not NAME.fullmatch(name):
        raise ValueError("invalid OpenAPI wrapper name")
    # The tiny launcher works with the same installed interpreter as the package.
    # Set the home explicitly so invoking the saved wrapper later still finds its registry.
    import shlex

    executable = executable or sys.executable
    code = (
        f"#!{executable}\n# Generated by {package}.openapi\nimport os, sys\n"
        f"os.environ['CLITW_HOME'] = {str(home().resolve())!r}\n"
        f"from {package}.openapi.native import execute\n"
        f"raise SystemExit(execute({name!r}, sys.argv[1:]))\n"
    )
    if " " in executable and os.name == "posix":
        code = (
            "#!/bin/sh\n" + "'''exec' " + shlex.quote(executable) + ' "$0" "$@"\n' + "' '''\n" + code.split("\n", 1)[1]
        )
    return code.encode()


def scoped_environment(private: Path | None = None) -> dict[str, str]:
    """Give native processes only OS essentials and the installed package location."""
    env = {
        k: os.environ[k] for k in ("PATH", "SYSTEMROOT", "WINDIR", "TMP", "TEMP", "TMPDIR", "LANG") if k in os.environ
    }
    private = private or home() / "openapi-runtime"
    private.mkdir(parents=True, exist_ok=True)
    env.update(
        HOME=str(private),
        USERPROFILE=str(private),
        CLITW_HOME=str(home().resolve()),
        MCP2CLI_CACHE_DIR=str(private / "cache"),
        MCP2CLI_CONFIG_DIR=str(private / "config"),
        PYTHONPATH=str(Path(__file__).resolve().parents[2]),
    )
    return env


def launcher(name: str) -> list[str]:
    return provider_argv(name)
