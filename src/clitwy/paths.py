"""Resolve the private clitwy installation independently from the user's mcp2cli registry."""

import os
import sys
from pathlib import Path

from filelock import FileLock


def home() -> Path:
    default = Path(os.environ.get("XDG_DATA_HOME", Path.home() / ".local/share")) / "clitw"
    return Path(os.environ.get("CLITW_HOME", default)).expanduser().resolve()


def bin_dir() -> Path:
    return home() / "bin"


def provider_path(name: str) -> Path:
    return bin_dir() / (f"{name}.py" if os.name == "nt" else name)


def provider_argv(name: str) -> list[str]:
    path = provider_path(name)
    if path.is_file() and not path.is_symlink() and path.stat().st_size <= 16384:
        body = path.read_bytes()
        if b"# Generated by clitw.openapi\n" in body and b"from clitw.openapi.native import execute" in body:
            from .openapi.upgrade import migrate_names

            migrate_names([name], require_exports=False)
        elif b"# managed by clitw mcp\n" in body and b"clitw.mcp.runtime" in body:
            from .mcp.install import migrate_names

            migrate_names([name])
        else:
            body = None
        if body is not None and path.exists() and path.read_bytes() == body:
            raise ValueError(f"{name}: legacy launcher does not match an installed provider receipt")
    return [sys.executable, str(path)] if os.name == "nt" else [str(path)]


def registry_dir() -> Path:
    return home() / "registry"


def install_lock() -> FileLock:
    home().mkdir(mode=0o700, parents=True, exist_ok=True)
    return FileLock(home() / "install.lock", timeout=180)
